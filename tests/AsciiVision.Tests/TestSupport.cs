internal static class TestFfmpeg
{
    private static readonly Lazy<FfmpegInstallation?> LazyInstallation = new(() => new FfmpegLocator().Locate(null));

    public static FfmpegInstallation? Installation => LazyInstallation.Value;

    private static readonly Lazy<string?> LazySample = new(CreateSample);

    /// <summary>A 2-second 320x180 25 fps test clip with a sine audio track, generated by ffmpeg itself.</summary>
    public static string? SampleVideo => LazySample.Value;

    private static string? CreateSample()
    {
        var ff = Installation;
        if (ff is null)
        {
            return null;
        }

        var dir = Path.Combine(Path.GetTempPath(), "AsciiVisionTests");
        Directory.CreateDirectory(dir);
        var path = Path.Combine(dir, "sample clip ü.mp4"); // space + non-ASCII on purpose
        if (File.Exists(path))
        {
            return path;
        }

        using var process = FfmpegProcess.Start(ff.FfmpegPath,
        [
            "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", "testsrc2=size=320x180:rate=25:duration=2",
            "-f", "lavfi", "-i", "sine=frequency=440:duration=2",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", "-shortest", path,
        ], redirectInput: false, redirectOutput: false);
        process.WaitForExitAsync(CancellationToken.None).GetAwaiter().GetResult();
        return File.Exists(path) ? path : null;
    }
}

/// <summary>A fact that is skipped when FFmpeg is not installed.</summary>
public sealed class FfmpegFactAttribute : FactAttribute
{
    public FfmpegFactAttribute()
    {
        if (TestFfmpeg.Installation is null)
        {
            Skip = "FFmpeg was not found on this machine.";
        }
    }
}
