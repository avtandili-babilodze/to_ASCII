/// <summary>Collects frames submitted by the pipeline (retaining clones so tests can inspect them later).</summary>
internal sealed class CollectingRenderer : ITerminalRenderer
{
    private readonly object _gate = new();
    private readonly List<AsciiFrame> _frames = new();

    public string Name => "Collector";
    public bool IsActive { get; set; } = true;
    public GridSize? TerminalSize { get; set; }
    public List<string> Statuses { get; } = new();

    public int Count
    {
        get { lock (_gate) { return _frames.Count; } }
    }

    public AsciiFrame[] Snapshot()
    {
        lock (_gate)
        {
            return _frames.ToArray();
        }
    }

    public void Submit(AsciiFrame frame)
    {
        lock (_gate)
        {
            _frames.Add(frame.Clone());
        }

        frame.Dispose();
    }

    public void ShowStatus(string message)
    {
        lock (_gate)
        {
            Statuses.Add(message);
        }
    }
}

internal static class TestImages
{
    /// <summary>Uniform gray frame.</summary>
    public static VideoFrame Solid(int width, int height, byte r, byte g, byte b)
    {
        var frame = VideoFrame.Rent(width, height, TimeSpan.Zero);
        var pixel = 0xFF000000u | ((uint)r << 16) | ((uint)g << 8) | b;
        System.Runtime.InteropServices.MemoryMarshal.Cast<byte, uint>(frame.Data).Fill(pixel);
        return frame;
    }

    /// <summary>Black frame with a white line drawn by OpenCV.</summary>
    public static unsafe VideoFrame Line(int width, int height, Point a, Point b, int thickness = 3)
    {
        var frame = Solid(width, height, 0, 0, 0);
        fixed (byte* p = frame.Buffer)
        {
            using var mat = Mat.FromPixelData(height, width, MatType.CV_8UC4, (IntPtr)p, frame.Stride);
            Cv2.Line(mat, a, b, new Scalar(255, 255, 255, 255), thickness, LineTypes.Link8);
        }

        return frame;
    }

    /// <summary>Horizontal gradient from black (left) to white (right).</summary>
    public static VideoFrame HorizontalGradient(int width, int height)
    {
        var frame = VideoFrame.Rent(width, height, TimeSpan.Zero);
        for (int y = 0; y < height; y++)
        {
            var row = System.Runtime.InteropServices.MemoryMarshal.Cast<byte, uint>(frame.GetRow(y));
            for (int x = 0; x < width; x++)
            {
                uint v = (uint)(x * 255 / (width - 1));
                row[x] = 0xFF000000u | (v << 16) | (v << 8) | v;
            }
        }

        return frame;
    }
}

